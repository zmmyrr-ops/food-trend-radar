export const bfReferences = [
  ...food.map(([tags, copy], i) => ({
    id: `food-${i + 1}`,
    channel: "food",
    tags,
    copy,
    source: bfSources[i % bfSources.length],
  })),
  ...leisure.map(([tags, copy], i) => ({
    id: `leisure-${i + 1}`,
    channel: "leisure",
    tags,
    copy,
    source: bfSources[i % bfSources.length],
  })),
];
export function selectBfReferences(
  channel: string | undefined,
  context: string,
) {
  return bfReferences
    .filter((x) => !channel || x.channel === channel)
    .map((x) => ({
      x,
      score: x.tags.split(" ").filter((t) => context.includes(t)).length,
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((x) => x.x);
}
