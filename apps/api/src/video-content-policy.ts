import type { VideoProject } from "./video-types.js";
export function contentPolicy(p: Pick<VideoProject, "channel" | "category">) {
  if (p.channel === "leisure")
    return {
      selection: `当前是游玩频道，分类${p.category || "游玩"}。设施、动物、展陈、主题布景、景观、运动、门头、导览图、演出、场馆环境均是有效主体。场馆设施和舞台整体全景可入选，背景游客不扣分；以特定真人为主体的跟拍、个人互动和人物展示不可入选，即使是侧脸、背影或全身也一样。没有食物绝不是拒绝理由。角色扮演服装、模拟商店属于亲子体验，不得仅凭服装陈列认定为无关服装店。展示价值看体验吸引力、空间特色、设施细节与场景丰富度，不要求有人参与，不推断门票权益。`,
      ordering:
        "按设施、动物或主题场景亮点开场，体验细节展开，全景收尾。门头可用于定位。不需要食物镜头。",
    };
  if (p.channel === "food")
    return {
      selection:
        "当前为餐饮频道。菜品、满桌摆盘、自助餐台、档口、饮品、制作动作、门头及用餐环境均可入选。稳定展示与动作同等对待，丰盛程度、份量、品类和质感均有价值，只有手或手臂展示饮品、夹菜和制作动作应正常入选；包装卡通人物不是真人，不得因此拒绝。不要求手或进食动作，不推断券内权益。",
      ordering:
        "吸引人的菜品或丰盛陈列开场，用餐过程自然推进，成品或全景收尾，门头环境辅助，自助餐可连续展示不同档口。",
    };
  return {
    selection:
      "当前为未分类自定义店铺。按店铺信息与实际画面判断，设施、动物、场景、食物均可入选。不默认套用餐饮标准，不因没有食物拒绝，不推断权益。",
    ordering: "视觉亮点开场、体验细节展开、完整场景收尾，不要求食物镜头。",
  };
}
